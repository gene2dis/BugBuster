#!/usr/bin/env python3
"""Write CITATIONS.md from the report's curated references (roadmap Phase 29, CL6; issue #25).

The tools and databases come from assets/report/tool_references.tsv (kinds tool and database
with a section; helpers and tools no module runs any more have none), their references from
assets/report/references.yml, the same two files the report's Methods cite from, so the list
and the report cannot drift. tests/bin/test_tool_references.sh runs this with --check, which
fails when the committed CITATIONS.md differs from what the files give.

Usage: make_citations.py [--check]   (run from anywhere; standard library only)
"""

import csv
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TSV = REPO / "assets" / "report" / "tool_references.tsv"
REFS = REPO / "assets" / "report" / "references.yml"
OUT = REPO / "CITATIONS.md"

# the order of the sections in CITATIONS.md: the pipeline's steps, as in the README
SECTIONS = [
    "Pipeline",
    "Read quality control, host removal and sequencing depth",
    "Read-level taxonomic profiling",
    "Read-level ARG prediction",
    "Assembly",
    "Binning, MAG quality and dereplication",
    "Gene calling and contig-level ARG prediction",
    "Contig taxonomy and viruses",
    "Functional annotation",
]

HEADER = """# Citations

<!-- Generated by tests/bin/make_citations.py from assets/report/tool_references.tsv and
assets/report/references.yml; edit those files, then run the script. -->

If you use BugBuster, cite the pipeline with its version (`nextflow run main.nf --version`)
and repository, https://github.com/gene2dis/BugBuster, and the tools and databases of the
steps you enabled. The Methods page of a run's report (`00_summary/report/`, and the PDF) lists
the ones that ran, with their versions; this file lists every tool and database the pipeline can
run, by pipeline step. Tools and databases that rest on the same publication share an entry.
"""


def load_refs(path):
    """references.yml: top-level keys, each with two-space-indented `field: value` lines."""
    refs, key = {}, None
    for line in path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^([A-Za-z0-9_-]+):\s*$", line)
        if m:
            key = m.group(1)
            refs[key] = {}
            continue
        m = re.match(r"^  ([a-z]+):\s*(.*)$", line)
        if not (m and key):
            sys.exit(f"make_citations.py: {path.name}: cannot read line: {line!r}")
        value = m.group(2).strip()
        if len(value) >= 2 and value[0] == value[-1] == '"':
            value = value[1:-1]
        refs[key][m.group(1)] = value
    return refs


def format_reference(r):
    """Authors. Title. Journal volume, pages (year). DOI link: the report's format, with a link."""
    authors = r.get("author", "").replace("{", "").replace("}", "")
    parts = [a.strip() for a in authors.split(" and ")] if authors else []
    if len(parts) > 5 or (parts and parts[-1] == "others"):
        names = ", ".join(p for p in parts[:3] if p != "others") + " et al."
    else:
        names = ", ".join(parts[:-1]) + (" & " if len(parts) > 1 else "") + (parts[-1] if parts else "")
    venue = r.get("journal") or r.get("publisher") or ""
    vol = f" {r['volume']}" if r.get("volume") else ""
    pages = f", {r['pages'].replace('--', '-')}" if r.get("pages") else ""
    link = f" [doi:{r['doi']}](https://doi.org/{r['doi']})" if r.get("doi") else f" <{r['url']}>" if r.get("url") else ""
    names = names if names.endswith(".") else names + "."
    return f"{names} {r.get('title', '')}. *{venue}*{vol}{pages} ({r.get('year', '')}).{link}"


def render():
    refs = load_refs(REFS)
    by_section = {s: {} for s in SECTIONS}  # section -> display name -> citekeys, in file order
    problems = []
    with open(TSV) as fh:
        for row in csv.DictReader((ln for ln in fh if not ln.startswith("#")), delimiter="\t"):
            section = (row.get("section") or "").strip()
            if not section:
                continue
            if row["kind"] == "helper":
                problems.append(f"{row['tool']}: a helper has no section")
                continue
            if section not in by_section:
                problems.append(f"{row['tool']}: unknown section '{section}' (SECTIONS in make_citations.py)")
                continue
            keys = [k for k in (row.get("references") or "").split(";") if k]
            for k in keys:
                if k not in refs:
                    problems.append(f"{row['tool']}: citekey '{k}' is not in references.yml")
            entry = by_section[section].setdefault(row["name"], [])
            entry.extend(k for k in keys if k not in entry)
    if problems:
        sys.exit("make_citations.py:\n" + "\n".join(f"  {p}" for p in problems))

    out = [HEADER]
    for section in SECTIONS:
        if not by_section[section]:
            continue
        out.append(f"## {section}\n")
        # names with the same references share one entry (sylph and sylph-tax), in file order
        groups = {}
        for name, keys in by_section[section].items():
            groups.setdefault(tuple(keys), []).append(name)
        for keys, names in groups.items():
            label = ", ".join(f"**{n}**" for n in names)
            if not keys:
                out.append(f"- {label}: no publication to cite.")
                continue
            out.append(f"- {label}")
            out.extend(f"  - {format_reference(refs[k])}" for k in keys)
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    text = render()
    if sys.argv[1:] == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("CITATIONS.md is not what tests/bin/make_citations.py writes from assets/report/"
                     "tool_references.tsv and references.yml: run tests/bin/make_citations.py and commit it")
        print("  ok: CITATIONS.md matches assets/report/tool_references.tsv and references.yml")
        return
    if sys.argv[1:]:
        sys.exit(__doc__)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
